import {readFile, writeFile} from 'node:fs/promises';
const root = new URL('../', import.meta.url);
const ledger = (await readFile(new URL('lib/ledger.js', root), 'utf8')).replace(/^export /gm, '');
const client = await readFile(new URL('src/client.js', root), 'utf8');
if (!client.includes('/* @ledger */')) throw new Error('Missing ledger insertion point');
await writeFile(new URL('lib/client.js', root), '// Generated by npm run build from src/client.js and lib/ledger.js.\n' + client.replace('/* @ledger */', () => ledger));
